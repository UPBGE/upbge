enum class LN_RequiredPhase : uint8_t {
  None = 0,
  OnInit,
  Update,
  FixedUpdate,
};

enum class LN_AutonomousPhase : uint8_t {
  None = 0,
  Update,
  FixedUpdate,
};

enum class LN_ExecutionClass : uint8_t {
  SnapshotReadOnly = 0,
  CommandEmitting,
  MainThreadOnly,
};

enum class LN_PinKind : uint8_t {
  Value = 0,
  Condition,
  Execution,
};

struct LN_PinDefinition {
  std::string name;
  std::string socket_idname;
  LN_PinKind kind = LN_PinKind::Value;
  LN_ValueType value_type = LN_ValueType::None;
  bool requires_link = false;
  bool allows_multiple_links = false;
  bool is_variadic = false;
};

struct LN_NodeDefinition {
  std::string idname;
  LN_NodeKind kind = LN_NodeKind::ValueBool;
  std::vector<LN_PinDefinition> inputs;
  std::vector<LN_PinDefinition> outputs;
  std::string category;
  std::string ui_name;
  std::string ui_description;
  bool has_side_effects = false;
  LN_RequiredPhase required_phase = LN_RequiredPhase::None;
  bool requires_jolt = false;
  bool future_pure_batchable = false;
  LN_ExecutionClass execution_class = LN_ExecutionClass::SnapshotReadOnly;
  LN_AutonomousPhase autonomous_phase = LN_AutonomousPhase::None;
};

class LN_NodeRegistry {
 public:
  LN_NodeRegistry();

  static const LN_NodeRegistry &GetBuiltin();

  const LN_NodeDefinition *FindNodeDefinition(const std::string &idname) const;
  /** The definition a node compiles with: its own, or for a merged node (NOD_logic_merged.hh) the
   * older node its option is (custom4), with the merged node's extra outputs. So an option
   * compiles exactly as the older node. Null for an unknown node type. */
  const LN_NodeDefinition *FindNodeDefinitionForNode(const blender::bNode &node) const;
  const std::vector<LN_NodeDefinition> &GetNodeDefinitions() const
  {
    return m_definitions;
  }

 private:
  std::vector<LN_NodeDefinition> m_definitions;
  /** Options of merged nodes that add outputs: the older node's definition plus those outputs,
   * keyed by the merged idname and the option ("idname:option"). */
  std::vector<std::pair<std::string, LN_NodeDefinition>> m_mergedDefinitions;
};
